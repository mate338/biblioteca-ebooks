const container = document.getElementById("ebooks");

ebooks.forEach((ebook, index) => {
  container.innerHTML += `
    <div class="card">
      <img src="${ebook.imagem}" onclick="abrirModal(${index})">
      <h3>${ebook.titulo}</h3>
      <p>${ebook.preco}</p>
      <button onclick="window.open('${ebook.link}')">
        Comprar agora
      </button>
    </div>
  `;
});

const texto = "Dreamer Library";
let i = 0;

function escrever() {
  if (i < texto.length) {
    document.getElementById("texto-titulo").innerHTML += texto.charAt(i);
    i++;
    setTimeout(escrever, 80); // velocidade (menor = mais rápido)
  } else {
    setTimeout(apagar, 1500); // espera antes de apagar
  }
}

function apagar() {
  if (i > 0) {
    document.getElementById("texto-titulo").innerHTML = texto.substring(0, i - 1);
    i--;
    setTimeout(apagar, 40);
  } else {
    setTimeout(escrever, 500);
  }
}

escrever();

function abrirModal(index) {
  const ebook = ebooks[index];

  document.getElementById("modalImagem").src = ebook.imagem;
  document.getElementById("modalTitulo").innerText = ebook.titulo;
  document.getElementById("modalDescricao").innerText = ebook.descricao;
  document.getElementById("modalPreco").innerText = ebook.preco;
  document.getElementById("modalLink").href = ebook.link;

  document.getElementById("modal").style.display = "flex";
}

document.getElementById("fecharModal").onclick = function () {
  document.getElementById("modal").style.display = "none";
};