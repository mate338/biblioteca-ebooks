function renderizarEbooks(lista) {

  container.innerHTML = "";

  if (lista.length === 0) {
    container.innerHTML = `
      <div class="sem-produtos">
        <h2>Nenhum produto encontrado</h2>
        <p>Produtos físicos serão adicionados em breve.</p>
      </div>
    `;
    return;
  }

  lista.forEach((ebook, index) => {
    container.innerHTML += `
      <div class="card">
        <img src="${ebook.imagem}" onclick='abrirModal(${JSON.stringify(ebook)})'

        <h3>${ebook.titulo}</h3>

        <p>${ebook.preco}</p>

        <button onclick="window.open('${ebook.link}')">
          Comprar agora
        </button>
      </div>
    `;
  });

}

